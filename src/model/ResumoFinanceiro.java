package model;

public class ResumoFinanceiro {
    private double receitas, despesas, pagas, pendentes, atrasadas, saldo;
    public double getReceitas() { return receitas; } public void setReceitas(double v) { receitas = v; }
    public double getDespesas() { return despesas; } public void setDespesas(double v) { despesas = v; }
    public double getPagas() { return pagas; } public void setPagas(double v) { pagas = v; }
    public double getPendentes() { return pendentes; } public void setPendentes(double v) { pendentes = v; }
    public double getAtrasadas() { return atrasadas; } public void setAtrasadas(double v) { atrasadas = v; }
    public double getSaldo() { return saldo; } public void setSaldo(double v) { saldo = v; }
}
