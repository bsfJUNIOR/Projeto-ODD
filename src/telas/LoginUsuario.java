    private void configurarAlternanciaSenha() {
        jLabel3.setToolTipText("Clique para mostrar ou ocultar a senha");
        jLabel3.setCursor(Cursor.getPredefinedCursor(Cursor.HAND_CURSOR));
        jLabel3.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                alternarSenha();
            }
        });
    }

    private void alternarSenha() {
        ctSenhaUsuario.setEchoChar(ctSenhaUsuario.getEchoChar() == (char) 0 ? '\u2022' : (char) 0);
    }

    private void entrar() {
        char[] senha = ctSenhaUsuario.getPassword();
        try {
            Usuario usuario = new UsuarioService().autenticar(ctUsuario.getText(), senha);
            if (usuario == null) {
                JOptionPane.showMessageDialog(this, "Usuário ou senha inválidos.", "Login", JOptionPane.WARNING_MESSAGE);
                ctSenhaUsuario.setText("");
                return;
            }
            SessaoUsuario.iniciar(usuario);
            new HistoricoService().registrar("LOGIN", "realizou login.");
            dispose();
            new MenuPrincipal().setVisible(true);
        } catch (RuntimeException e) {
            SessaoUsuario.encerrar();
            JOptionPane.showMessageDialog(this, "Não foi possível realizar o login. Verifique a conexão com o banco.", "Login", JOptionPane.ERROR_MESSAGE);
        } finally {
            Arrays.fill(senha, '\0');
        }
    }

